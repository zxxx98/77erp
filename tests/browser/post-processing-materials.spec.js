import { test, expect, devices } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { createApp } from '../../server/app.js';
import { productionAction } from './production-ui-helpers.js';

for (const mode of ['desktop', 'Pixel 7', 'iPhone 13', 'pwa']) test(`${mode} plans and consumes fixed post-processing materials`, async ({ browser }) => {
  test.setTimeout(60000);
  const context = await browser.newContext({ locale: 'zh-CN', ...(mode === 'desktop' ? {} : devices[mode === 'pwa' ? 'iPhone 13' : mode]), serviceWorkers: mode === 'pwa' ? 'allow' : 'block' });
  const page = await context.newPage();
  const { app, db } = createApp(':memory:');
  const server = app.listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  const base = `http://127.0.0.1:${server.address().port}`;
  const post = async (path, data) => {
    const response = await page.request.post(`${base}/api${path}`, { data: { request_id: randomUUID(), schema_version: 2, stage_schema_version: 1, operation_schema_version: 1, ...data } });
    const result = await response.json();
    expect(response.ok(), JSON.stringify(result)).toBe(true);
    return result;
  };
  const button = (name, container = page) => container.getByRole('button', { name, exact: true });
  const label = name => page.getByLabel(name, { exact: true });
  const expectPageFits = async () => expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  page.on('dialog', prompt => prompt.accept());
  try {
    await post('/auth/setup', { username: 'postadmin', password: 'Test-admin-123' });
    await post('/settings/reset', { confirmation: 'RESET_BUSINESS_DATA' });
    const product = name => post('/products', { name, barcode: randomUUID(), category: '生产', unit: '件', cost: 1, price: 2, threshold: 0 });
    const output = await product('包装成品'), raw = await product('包装材料');
    db.prepare('UPDATE products SET stock=200,inventory_value_cents=20000 WHERE id=?').run(raw.id);
    await post('/boms', { product_id: output.id, name: '成品配方', base_quantity: 1, base_unit: '件', enabled: 1, note: '', items: [{ product_id: raw.id, quantity: 1, unit: '件', note: '' }] });
    await page.goto(`${base}/#process-routes`);
    if (mode === 'pwa') await page.evaluate(() => navigator.serviceWorker.ready);
    await button('新建路线').click();
    await label('路线名称').fill('固定包装模板');
    await expect(label('搜索材料')).toHaveCount(0);
    await page.getByRole('combobox', { name: '工艺分类', exact: true }).click();
    await page.getByRole('option', { name: '后处理工艺', exact: true }).click();
    await label('工序名称').fill('包装');
    await expect(label('搜索材料')).toBeVisible({ timeout: 3000 });
    await label('搜索材料').fill('包装材料');
    await button('添加材料 包装材料').click();
    await label('每次用量 包装材料').fill('0.00001');
    await button('保存路线').click();
    await expect(page.getByRole('alert')).toContainText('最多 4 位小数');
    await label('每次用量 包装材料').fill('2');
    await expectPageFits();
    await button('保存路线').click();
    await expect(page.locator('.bom-success')).toContainText('工艺路线已保存');

    await page.goto(`${base}/#production`);
    await button('新建生产单').click();
    await page.getByRole('button', { name: /^选择配方 包装成品 ·/ }).click();
    await label('计划产量').fill('110');
    await button('添加后处理工序').click();
    const picker = page.getByRole('dialog', { name: '添加后处理工序' });
    await button('固定包装模板', picker).click();
    await button('包装', picker).click();
    await label('每次处理成品数量 包装').fill('20');
    const plan = page.locator('.post-processing-plan');
    await expect(plan).toContainText('预计 6 次');
    await expect(plan).toContainText('预计用量 12 件');
    await expectPageFits();
    const created = page.waitForRequest(request => request.method() === 'POST' && new URL(request.url()).pathname === '/api/production-orders');
    await button('保存生产草稿').click();
    expect((await created).postDataJSON().post_processing_operations[0]).not.toHaveProperty('materials');
    await expect(page.locator('.bom-success')).toContainText('库存未变动');
    const { id } = db.prepare('SELECT id FROM production_orders ORDER BY id DESC LIMIT 1').get();
    const getOrder = async () => (await page.request.get(`${base}/api/production-orders/${id}`)).json();
    await button('开始生产').click();
    await expect(page.locator('.production-material').filter({ hasText: '包装材料' }).filter({ hasText: '122' })).toBeVisible();
    await button('提交领料申请').click();
    const order = await getOrder();
    await post(`/production-material-documents/${order.material_documents[0].id}/confirm`, { version: order.material_documents[0].version });
    await productionAction(page, '刷新单据与库存');
    await page.getByRole('tab', { name: '物料', exact: true }).click();
    const ledger = page.getByRole('table', { name: '生产物料台账' });
    await expect(ledger.locator('[data-field="planned_quantity"]')).toContainText('122 件');
    await button('查看详情 包装材料', ledger).click();
    await expect(ledger).toContainText('配方需求');
    await expect(ledger).toContainText('后处理需求');

    await button('登记').click();
    await page.getByRole('radio', { name: /包装成品/ }).click();
    await label('本次数量').fill('110');
    await button('提交登记').click();
    await expect(page.getByRole('status').filter({ hasText: '已登记 包装成品' })).toBeVisible();
    if (mode === 'desktop') await button('登记').click();
    await page.getByRole('radio', { name: /包装.*后处理工序/ }).click();
    await label('本次数量').fill('7');
    const preview = page.getByRole('region', { name: '本次固定耗料' });
    await expect(preview).toContainText('缺料 2 件');
    await label('本次数量').fill('6');
    await expect(preview).toContainText('本次用量 12 件');
    await expect(preview).toContainText('已领余量 12 件');
    await expect(preview.getByText('材料已停用，或单位、取整规则已变化。', { exact: true })).toHaveCount(0);
    await expect(preview.getByRole('textbox')).toHaveCount(0);
    await expectPageFits();
    await preview.evaluate(element => element.scrollIntoView({ block: 'center' }));
    await page.screenshot({ path: test.info().outputPath('fixed-material-preview.png'), animations: 'disabled' });
    await preview.screenshot({ path: test.info().outputPath('fixed-material-preview-detail.png'), animations: 'disabled' });
    await button('提交登记').click();
    await expect(page.getByRole('status').filter({ hasText: '已登记 包装' })).toContainText('6 次');
    if (mode !== 'desktop') await button('返回单据详情').click();
    await page.getByRole('tab', { name: '概览', exact: true }).click();
    await page.getByText('单据资料与操作记录', { exact: true }).click();
    await expect(page.getByText(/本单总耗料成本.*122\.00/)).toBeVisible();
    await page.getByRole('tab', { name: '生产进度', exact: true }).click();
    const operation = page.locator('.production-progress-item').filter({ hasText: '包装' });
    await operation.locator('summary').click();
    await button('查看工序记录', operation).click();
    await expect(page.locator('.process-history-card')).toContainText('包装材料');
    await expect(page.locator('.process-history-card')).toContainText('12 件');
    await expect(page.locator('.process-history-card')).toContainText('后处理材料成本');
    await expectPageFits();
  } finally {
    await context.close();
    server.closeAllConnections();
    await new Promise(resolve => server.close(resolve));
    db.close();
  }
});
