import { test, expect, devices } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { createApp } from '../../server/app.js';

for (const mode of ['desktop', 'mobile', 'pwa']) test(`${mode} production workspace keeps progress visible and uses one registration flow`, async ({ browser }) => {
  const context = await browser.newContext({ locale: 'zh-CN', ...(mode === 'desktop' ? { viewport: { width: 1440, height: 1000 } } : devices['iPhone 13']), serviceWorkers: mode === 'pwa' ? 'allow' : 'block' });
  const page = await context.newPage();
  const { app, db } = createApp(':memory:');
  const server = app.listen(0, '127.0.0.1'); await new Promise(resolve => server.once('listening', resolve));
  const base = `http://127.0.0.1:${server.address().port}`;
  const post = async (path, body) => {
    const response = await page.request.post(`${base}/api${path}`, { data: { request_id: randomUUID(), schema_version: 2, stage_schema_version: 1, operation_schema_version: 1, ...body } });
    const result = await response.json(); expect(response.ok(), JSON.stringify(result)).toBe(true); return result;
  };
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  try {
    await post('/auth/setup', { username: 'workspaceadmin', password: 'Test-admin-123' });
    await post('/settings/reset', { confirmation: 'RESET_BUSINESS_DATA' });
    const route = await post('/process-routes', { name: '加工路线', enabled: 1, note: '', graph: { nodes: [{ id: 'cut', name: '下料', note: '', x: 0, y: 0 }, { id: 'output', name: '成品检验', note: '', x: 220, y: 0 }], edges: [{ from: 'cut', to: 'output' }] } });
    const product = (name, default_route_id = null) => post('/products', { name, barcode: randomUUID(), category: '生产', unit: '件', cost: 1, price: 2, threshold: 0, default_route_id });
    const output = await product('电缆接头', route.id), raw = await product('铜料');
    db.prepare('UPDATE products SET stock=100, inventory_value_cents=10000 WHERE id=?').run(raw.id);
    const bom = await post('/boms', { product_id: output.id, name: '接头配方', base_quantity: 1, base_unit: '件', enabled: 1, note: '', items: [{ product_id: raw.id, quantity: 2, unit: '件', note: '' }] });
    let order = await post('/production-orders', { bom_id: bom.id, bom_version: bom.version, planned_quantity: 2, note: '客户急单' });
    const get = async () => (await page.request.get(`${base}/api/production-orders/${order.id}`)).json();
    await page.goto(`${base}/#production`);
    if (mode === 'pwa') await page.evaluate(() => navigator.serviceWorker.ready);
    await page.getByRole('button', { name: `查看生产单 ${order.number}`, exact: true }).click();
    const summary = page.getByRole('region', { name: '生产入库进度' });
    await expect(summary).toBeInViewport({ ratio: 1 });
    await expect(page.getByRole('button', { name: '开始生产', exact: true })).toBeVisible();
    await expect(page.getByRole('button', { name: '作废生产单', exact: true })).toHaveCount(0);
    await expect(page.getByRole('img', { name: '生产登记二维码' })).toHaveCount(0);
    await expect(page.getByText(/根配方损耗计算方式/)).not.toBeVisible();
    await page.screenshot({ path: test.info().outputPath(`${mode}-overview.png`), fullPage: true });
    await page.getByRole('button', { name: '更多操作', exact: true }).click();
    await expect(page.getByRole('img', { name: '生产登记二维码' })).toBeVisible();
    await expect(page.getByRole('button', { name: '导出 PDF', exact: true })).toBeVisible();
    await page.getByRole('button', { name: '刷新单据与库存', exact: true }).click();
    await page.getByRole('button', { name: '开始生产', exact: true }).click();
    await page.getByRole('button', { name: '提交领料申请', exact: true }).click();
    await expect(page.getByRole('region', { name: '当前待办' })).toContainText('等待仓库');
    order = await get(); await post(`/production-material-documents/${order.material_documents[0].id}/confirm`, { version: order.material_documents[0].version });
    await page.getByRole('button', { name: '更多操作', exact: true }).click();
    await page.getByRole('button', { name: '刷新单据与库存', exact: true }).click();
    await page.getByRole('tab', { name: '生产进度', exact: true }).click();
    await page.getByText('工序进度与登记（2）', { exact: true }).click();
    await page.getByRole('button', { name: '登记 下料', exact: true }).click();
    await expect(page.locator('.production-quick-registration')).toBeVisible();
    await expect(page.getByRole('radio', { name: /下料/ })).toBeChecked();
    await page.getByLabel('本次数量', { exact: true }).fill('2');
    await page.getByRole('button', { name: '提交登记', exact: true }).click();
    await expect(page.getByRole('status').filter({ hasText: '已登记' })).toBeVisible();
    await page.getByRole('button', { name: '返回单据详情', exact: true }).click();
    await page.getByRole('button', { name: '登记', exact: true }).click();
    await expect(page.locator('.production-quick-registration')).toBeVisible();
    await page.getByRole('radio', { name: /成品检验/ }).click();
    await page.getByLabel('本次数量', { exact: true }).fill('2');
    await expect(page.getByLabel('铜料实际耗料', { exact: true })).not.toBeVisible();
    await page.getByRole('button', { name: '提交登记', exact: true }).click();
    await expect(page.getByRole('status').filter({ hasText: '已登记' })).toBeVisible();
    order = await get(); expect(order.status).toBe('in_progress'); expect(order.pending_receipt_quantity).toBe(2);
    expect(db.prepare('SELECT stock FROM products WHERE id=?').get(output.id).stock).toBe(0);
    await page.getByRole('button', { name: '返回单据详情', exact: true }).click();
    await page.getByRole('tab', { name: '概览', exact: true }).click();
    await expect(page.getByRole('region', { name: '当前待办' })).toContainText('待仓库入库 2 件');
    page.once('dialog', dialog => dialog.accept());
    await page.getByRole('button', { name: '结束生产', exact: true }).click();
    await expect(page.getByText('已完工', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: '返回生产单', exact: true }).click();
    await page.getByRole('group', { name: '生产单快捷筛选' }).getByRole('button', { name: '待入库', exact: true }).click();
    await expect(page.locator('.production-list article')).toHaveCount(1);
    await page.screenshot({ path: test.info().outputPath(`${mode}-list.png`), fullPage: true });
    order = await get(); await post(`/production-receipts/${order.receipt_documents[0].id}/confirm`, { version: order.receipt_documents[0].version });
    await page.reload();
    await page.getByRole('group', { name: '生产单快捷筛选' }).getByRole('button', { name: '待入库', exact: true }).click();
    await expect(page.locator('.production-list article')).toHaveCount(0);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    expect(errors).toEqual([]);
  } finally { await context.close(); server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); db.close(); }
});
