import { test, expect, devices } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { createApp } from '../../server/app.js';
import { productionRegistrationUrl } from '../../shared/production-link.js';
import { productionAction } from './production-ui-helpers.js';

for (const mode of ['desktop', 'Pixel 7', 'iPhone 13', 'pwa']) test(`${mode} creates and registers order-only operations without changing the BOM or output`, async ({ browser }) => {
  test.setTimeout(60000);
  const context = await browser.newContext({ locale: 'zh-CN', ...(mode === 'desktop' ? {} : devices[mode === 'pwa' ? 'iPhone 13' : mode]), serviceWorkers: mode === 'pwa' ? 'allow' : 'block' });
  const page = await context.newPage(), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const { app, db } = createApp(':memory:');
  const server = app.listen(0, '127.0.0.1'); await new Promise(resolve => server.once('listening', resolve));
  const base = `http://127.0.0.1:${server.address().port}`;
  const post = async (path, body) => {
    const response = await page.request.post(`${base}/api${path}`, { data: { request_id: randomUUID(), schema_version: 2, stage_schema_version: 1, operation_schema_version: 1, ...body } });
    const result = await response.json(); expect(response.ok(), JSON.stringify(result)).toBe(true); return result;
  };
  try {
    await post('/auth/setup', { username: 'extraadmin', password: 'Test-admin-123' });
    await post('/settings/reset', { confirmation: 'RESET_BUSINESS_DATA' });
    const graph = { nodes: [{ id: 'cut', name: '下料', note: '', x: 24, y: 24 }, { id: 'out', name: '外观检查', note: '', x: 244, y: 24 }], edges: [{ from: 'cut', to: 'out' }] };
    await post('/process-routes', { name: '附加工序选择路线', note: '', enabled: 1, graph });
    const product = name => post('/products', { name, barcode: randomUUID(), category: '生产', unit: '件', cost: 1, price: 2, threshold: 0 });
    const output = await product('附加工序成品'), raw = await product('原材料'), cleaner = await product('清洗剂');
    db.prepare('UPDATE products SET stock=100,inventory_value_cents=10000 WHERE id=?').run(raw.id);
    db.prepare('UPDATE products SET stock=10,inventory_value_cents=1000 WHERE id=?').run(cleaner.id);
    const bom = await post('/boms', { product_id: output.id, name: '原始配方', base_quantity: 1, base_unit: '件', enabled: 1, note: '', items: [{ product_id: raw.id, quantity: 2, unit: '件', note: '' }] });
    const originalBom = db.prepare('SELECT * FROM boms WHERE id=?').get(bom.id);
    await page.goto(`${base}/#production`);
    if (mode === 'pwa') await page.evaluate(() => navigator.serviceWorker.ready);
    await page.getByRole('button', { name: '新建生产单', exact: true }).click();
    await page.getByRole('button', { name: /^选择配方 附加工序成品 ·/ }).click();
    await page.getByLabel('计划产量', { exact: true }).fill('10');
    await page.getByRole('button', { name: '添加附加工序', exact: true }).click();
    const picker = page.getByRole('dialog', { name: '添加附加工序', exact: true });
    await picker.getByRole('searchbox', { name: '搜索工艺路线', exact: true }).fill('附加工序选择路线');
    await picker.getByRole('button', { name: '附加工序选择路线', exact: true }).click();
    await picker.getByRole('button', { name: '外观检查', exact: true }).click();
    await page.getByLabel('附加工序数量 外观检查', { exact: true }).fill('3');
    const planMaterials = page.locator('.additional-operation-plan');
    for (const [name, quantity] of [['原材料', '6'], ['清洗剂', '3']]) {
      await planMaterials.getByRole('searchbox').fill(name);
      await planMaterials.getByRole('button', { name: `添加材料 ${name}`, exact: true }).click();
      await planMaterials.getByLabel(`外观检查 ${name} 附加工序计划用料`, { exact: true }).fill(quantity);
    }
    await page.getByRole('button', { name: '保存生产草稿', exact: true }).click();
    await expect(page.locator('.bom-success')).toContainText('库存未变动');
    let order = db.prepare('SELECT * FROM production_orders ORDER BY id DESC LIMIT 1').get();
    const get = async () => (await page.request.get(`${base}/api/production-orders/${order.id}`)).json();
    await page.getByRole('button', { name: '开始生产', exact: true }).click();
    await expect(page.getByLabel('原材料领料数量', { exact: true })).toHaveValue('26');
    await expect(page.getByLabel('清洗剂领料数量', { exact: true })).toHaveValue('3');
    await page.getByRole('button', { name: '提交领料申请', exact: true }).click();
    order = await get();
    await post(`/production-material-documents/${order.material_documents[0].id}/confirm`, { version: order.material_documents[0].version });
    await productionAction(page, '刷新单据与库存');
    await page.getByRole('tab', { name: '生产进度', exact: true }).click();
    const extraProgress = page.locator('.production-progress-item').filter({ hasText: '外观检查' });
    await expect(extraProgress).toContainText('附加工序');
    await expect(extraProgress).toContainText('0 / 3 件');
    await extraProgress.locator('summary').click();
    await extraProgress.getByRole('button', { name: '登记 外观检查', exact: true }).click();
    await expect(page.getByRole('radio', { name: /外观检查.*附加工序/ })).toBeChecked();
    await page.getByLabel('本次数量', { exact: true }).fill('2');
    await expect(page.getByLabel('原材料实际耗料', { exact: true })).toHaveValue('4');
    await expect(page.getByLabel('清洗剂实际耗料', { exact: true })).toHaveValue('2');
    await page.getByLabel('原材料实际耗料', { exact: true }).fill('5');
    await page.getByLabel('清洗剂实际耗料', { exact: true }).fill('1.5');
    await page.getByLabel('原材料耗料差异原因', { exact: true }).fill('额外清洗耗用');
    await page.getByRole('button', { name: '提交登记', exact: true }).click();
    await expect(page.getByRole('status').filter({ hasText: '已登记 外观检查' })).toBeVisible();
    await page.getByLabel('本次数量', { exact: true }).fill('2');
    await page.getByRole('button', { name: '提交登记', exact: true }).click();
    await expect(page.getByRole('alert')).toBeVisible();
    await expect(page.getByLabel('本次数量', { exact: true })).toHaveValue('2');
    await page.getByLabel('本次数量', { exact: true }).fill('');
    const workspace = await (await page.request.get(`${base}/api/workspace`)).json();
    await page.goto(productionRegistrationUrl({ origin: base, warehouseId: 1, orderId: order.id, number: order.number, sourceId: workspace.instance_id }));
    await page.getByRole('radio', { name: /外观检查.*附加工序/ }).click();
    await page.getByLabel('本次数量', { exact: true }).fill('1');
    await page.getByRole('button', { name: '提交登记', exact: true }).click();
    await expect(page.getByRole('status').filter({ hasText: '已登记 外观检查' })).toBeVisible();
    order = await get();
    expect(order.completed_quantity ?? 0).toBe(0);
    expect(order.receipt_documents).toHaveLength(0);
    expect(order.items.find(item => item.product_id === raw.id).available_quantity).toBe(19);
    expect(order.items.find(item => item.product_id === raw.id).consumed_quantity).toBe(7);
    expect(order.items.find(item => item.product_id === cleaner.id).available_quantity).toBe(0.5);
    expect(order.additional_material_cost_cents).toBe(950);
    expect(order.operation_routes[0].operations[0].completed_quantity).toBe(3);
    expect(order.operation_routes[0].reports).toHaveLength(2);
    expect(db.prepare('SELECT stock FROM products WHERE id=?').get(output.id).stock).toBe(0);
    expect(db.prepare('SELECT * FROM boms WHERE id=?').get(bom.id)).toEqual(originalBom);
    await page.getByRole('button', { name: '返回单据详情', exact: true }).click();
    await page.getByRole('tab', { name: '生产进度', exact: true }).click();
    await extraProgress.locator('summary').click();
    await extraProgress.getByRole('button', { name: '查看工序记录', exact: true }).click();
    await expect(page.locator('.process-history-card')).toHaveCount(2);
    await expect(page.locator('.process-history-list')).toContainText('额外清洗耗用');
    await expect(page.locator('.process-history-list')).toContainText('清洗剂');
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: test.info().outputPath('additional-operation-history.png'), fullPage: true });
    await page.goto(`${base}/#payroll`);
    await page.getByRole('combobox', { name: '成员', exact: true }).click();
    await page.getByRole('option', { name: /extraadmin/ }).click();
    await expect(page.locator('.payroll-report')).toHaveCount(2);
    await expect(page.locator('.payroll-reports')).toContainText('附加工序');
    await expect(page.locator('.payroll-reports')).not.toContainText('@extra:');
    expect(errors).toEqual([]);
  } finally {
    await context.close(); server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); db.close();
  }
});
