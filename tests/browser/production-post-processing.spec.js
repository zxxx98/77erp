import { test, expect, devices } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { createApp } from '../../server/app.js';
import { productionAction } from './production-ui-helpers.js';

for (const mode of ['desktop', 'Pixel 7', 'iPhone 13', 'pwa']) test(`${mode} binds post-processing and gates completion on actual output and every operation`, async ({ browser }) => {
  test.setTimeout(60000);
  const context = await browser.newContext({ locale: 'zh-CN', ...(mode === 'desktop' ? {} : devices[mode === 'pwa' ? 'iPhone 13' : mode]), serviceWorkers: mode === 'pwa' ? 'allow' : 'block' });
  const page = await context.newPage();
  page.setDefaultTimeout(12000);
  const { app, db } = createApp(':memory:');
  const server = app.listen(0, '127.0.0.1'); await new Promise(resolve => server.once('listening', resolve));
  const base = `http://127.0.0.1:${server.address().port}`;
  const post = async (path, body) => {
    const response = await page.request.post(`${base}/api${path}`, { data: { request_id: randomUUID(), schema_version: 2, stage_schema_version: 1, operation_schema_version: 1, ...body } });
    const result = await response.json(); expect(response.ok(), JSON.stringify(result)).toBe(true); return result;
  };
  const button = (name, container = page) => container.getByRole('button', { name, exact: true });
  const dialog = name => page.getByRole('dialog', { name, exact: true });
  const more = () => button('更多操作').click();
  page.on('dialog', prompt => prompt.accept());
  try {
    await post('/auth/setup', { username: 'postadmin', password: 'Test-admin-123' });
    await post('/settings/reset', { confirmation: 'RESET_BUSINESS_DATA' });
    await page.goto(`${base}/#process-routes`);
    if (mode === 'pwa') await page.evaluate(() => navigator.serviceWorker.ready);
    await button('新建路线').click();
    await page.getByLabel('路线名称', { exact: true }).fill('后处理模板');
    await page.getByRole('combobox', { name: '工艺分类', exact: true }).click();
    await page.getByRole('option', { name: '后处理工艺', exact: true }).click();
    await page.getByLabel('工序名称', { exact: true }).fill('包装');
    await button('保存路线').click();
    await expect(page.locator('.bom-success')).toContainText('工艺路线已保存');
    await page.getByRole('combobox', { name: '工艺分类', exact: true }).click();
    await page.getByRole('option', { name: '后处理工艺', exact: true }).click();
    await expect(page.locator('.process-route-card').filter({ hasText: '后处理模板' })).toContainText('后处理工艺');
    const graph = { nodes: [{ id: 'label', name: '贴标', note: '', x: 24, y: 24 }], edges: [] };
    await post('/process-routes', { name: '贴标模板', note: '', route_kind: 'post_processing', enabled: 1, graph });
    await post('/process-routes', { name: '普通生产模板', note: '', enabled: 1, graph });
    const product = name => post('/products', { name, barcode: randomUUID(), category: '生产', unit: '件', cost: 1, price: 2, threshold: 0 });
    const output = await product('后处理成品'), raw = await product('原材料');
    db.prepare('UPDATE products SET stock=200,inventory_value_cents=20000 WHERE id=?').run(raw.id);
    await post('/boms', { product_id: output.id, name: '原始配方', base_quantity: 1, base_unit: '件', enabled: 1, note: '', items: [{ product_id: raw.id, quantity: 1, unit: '件', note: '' }] });
    await page.goto(`${base}/#production`);
    await button('新建生产单').click();
    await page.getByRole('button', { name: /^选择配方 后处理成品 ·/ }).click();
    await page.getByLabel('计划产量', { exact: true }).fill('110');
    await expect(button('添加附加工序')).toHaveCount(0);
    for (const [route, node, coefficient] of [['后处理模板', '包装', '20'], ['贴标模板', '贴标', '50']]) {
      await button('添加后处理工序').click();
      const picker = dialog('添加后处理工序');
      await button(route, picker).waitFor();
      await expect(button('普通生产模板', picker)).toHaveCount(0);
      await button(route, picker).click();
      await button(node, picker).click();
      await page.getByLabel(`每次处理成品数量 ${node}`, { exact: true }).fill(coefficient);
    }
    await expect(page.locator('.post-processing-plan')).toContainText('预计 6 次');
    const created = page.waitForRequest(request => request.method() === 'POST' && new URL(request.url()).pathname === '/api/production-orders');
    await button('保存生产草稿').click();
    expect((await created).postDataJSON()).not.toHaveProperty('additional_operations');
    await expect(page.locator('.bom-success')).toContainText('库存未变动');
    const { id } = db.prepare('SELECT id FROM production_orders ORDER BY id DESC LIMIT 1').get();
    const get = async () => (await page.request.get(`${base}/api/production-orders/${id}`)).json();
    await button('开始生产').click();
    await button('提交领料申请').click();
    let order = await get();
    await post(`/production-material-documents/${order.material_documents[0].id}/confirm`, { version: order.material_documents[0].version });
    await productionAction(page, '刷新单据与库存');
    await more();
    await expect(button('结束生产', dialog('更多操作'))).toBeDisabled();
    await page.keyboard.press('Escape');
    await page.getByRole('tab', { name: '生产进度', exact: true }).click();
    const packing = page.locator('.production-progress-item').filter({ hasText: '包装' });
    await expect(packing).toContainText('等待成品产出');
    await button('登记').click();
    await page.getByRole('radio', { name: /后处理成品/ }).click();
    await page.getByLabel('本次数量', { exact: true }).fill('101');
    await button('提交登记').click();
    await expect(page.getByRole('status').filter({ hasText: '已登记 后处理成品' })).toBeVisible();
    await button('返回单据详情').click();
    await more();
    await expect(dialog('更多操作')).toContainText('包装还需 5 次');
    await expect(dialog('更多操作')).toContainText('贴标还需 2 次');
    await page.screenshot({ path: test.info().outputPath('post-processing-finish-gaps.png'), animations: 'disabled' });
    await button('确认成品生产完成', dialog('更多操作')).click();
    await expect(page.getByRole('status').filter({ hasText: '已确认成品生产完成' })).toBeVisible();
    await more();
    await button('撤销成品生产完成确认', dialog('更多操作')).click();
    await expect(page.getByRole('status').filter({ hasText: '已撤销成品生产完成确认' })).toBeVisible();
    await more();
    await button('确认成品生产完成', dialog('更多操作')).click();
    await expect(page.getByRole('status').filter({ hasText: '已确认成品生产完成' })).toBeVisible();
    await page.getByRole('tab', { name: '生产进度', exact: true }).click();
    await expect(packing).toContainText('0 / 6 次');
    await page.screenshot({ path: test.info().outputPath('post-processing-progress.png'), animations: 'disabled', fullPage: true });
    await packing.locator('summary').click();
    await button('登记 包装', packing).click();
    await expect(page.getByRole('radio', { name: /后处理成品/ })).toBeDisabled();
    await page.getByLabel('本次数量', { exact: true }).fill('1.5');
    await button('提交登记').click();
    await expect(page.getByRole('alert')).toBeVisible();
    await page.getByLabel('本次数量', { exact: true }).fill('6');
    await button('提交登记').click();
    await expect(page.getByRole('status').filter({ hasText: '已登记 包装' })).toContainText('6 次');
    await page.getByRole('radio', { name: /贴标.*后处理工序/ }).click();
    await page.getByLabel('本次数量', { exact: true }).fill('3');
    await button('提交登记').click();
    await expect(page.getByRole('status').filter({ hasText: '已登记 贴标' })).toContainText('3 次');
    await button('返回单据详情').click();
    await more();
    await expect(button('结束生产', dialog('更多操作'))).toBeEnabled();
    await button('结束生产', dialog('更多操作')).click();
    await expect(page.getByRole('status').filter({ hasText: '生产已结束' })).toBeVisible();
    order = await get();
    expect(order.completed_quantity).toBe(101);
    expect(order.status).toBe('completed');
    expect(order.receipt_documents).toHaveLength(1);
    await page.getByRole('tab', { name: '生产进度', exact: true }).click();
    await packing.locator('summary').click();
    await button('查看工序记录', packing).click();
    await expect(page.locator('.process-history-card')).toContainText('包装 · 6 次');
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  } finally {
    await context.close(); server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); db.close();
  }
});
